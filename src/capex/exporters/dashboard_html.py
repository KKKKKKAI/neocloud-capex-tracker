def generate_dashboard_html(
    output: str | Path | None = None,
    db_path: str | Path | None = None,
) -> Path:
    """Write the dashboard to `output` (defaults to docs/index.html)."""
    output = Path(output or DOCS_DIR / "index.html")
    output.parent.mkdir(parents=True, exist_ok=True)
    db_path = Path(db_path) if db_path else DB_PATH

    # Mirror thumbnails into the docs/ tree so GitHub Pages can serve
    # them. Keeps the source-of-truth in charts/ for README embedding.
    _mirror_thumbnails(output.parent / "charts")

    stats = _load_stats(db_path)
    nav_html = _build_nav_html("home")
    cards_html = _render_cards()
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    html_str = _HTML_TEMPLATE.format(
        nav_html=nav_html,
        cards_html=cards_html,
        company_count=stats["companies"],
        datapoint_count=f"{stats['extractions']:,}",
        latest_filing_date=html.escape(stats["latest_filing_date"] or "—"),
        generated=html.escape(generated),
    )
    output.write_text(html_str, encoding="utf-8")
    return output


def _mirror_thumbnails(dest_dir: Path) -> None:
    """Copy chart PNGs from `charts/` into the dashboard's `charts/` folder.

    Silent on missing PNGs: a chart that hasn't been generated yet simply
    shows the card without a thumbnail (browser's broken-image fallback).
    """
    dest_dir.mkdir(parents=True, exist_ok=True)
    for card in CHART_CARDS:
        src = CHARTS_DIR / card["png"]
        if src.exists():
            shutil.copy2(src, dest_dir / card["png"])


def _load_stats(db_path: Path) -> dict:
    """Tiny summary line: # companies, # extractions, newest filing date.

    Kept defensive so a missing / fresh DB doesn't blow up the
    dashboard render (the page is still useful without the line).
    """
    defaults = {"companies": 0, "extractions": 0, "latest_filing_date": ""}
    if not db_path.exists():
        return defaults
    try:
        conn = sqlite3.connect(str(db_path))
        conn.row_factory = sqlite3.Row
        n_co = conn.execute("SELECT COUNT(*) AS n FROM companies").fetchone()
        n_ex = conn.execute("SELECT COUNT(*) AS n FROM extractions").fetchone()
        latest = conn.execute(
            "SELECT MAX(filing_date) AS d FROM source_documents"
        ).fetchone()
        conn.close()
    except sqlite3.Error:
        return defaults
    return {
        "companies": n_co["n"] if n_co else 0,
        "extractions": n_ex["n"] if n_ex else 0,
        "latest_filing_date": (latest["d"] if latest else "") or "",
    }


def _render_cards() -> str:
    pieces = [_render_chart_card(c) for c in CHART_CARDS]
    pieces.append(_render_calendar_card())
    pieces.append(_render_treatments_card())
    return "\n".join(pieces)


def _render_chart_card(card: dict) -> str:
    cfg = METRIC_CONFIGS[card["metric_key"]]
    title = html.escape(cfg["nav_label"])
    subtitle = html.escape(card["subtitle"])
    href = html.escape(cfg["page_name"])
    png = html.escape(f"charts/{card['png']}")
    accent = html.escape(card["accent"])
    return (
        f'<a class="card chart-card" href="{href}" '
        f'style="--accent:{accent};">'
        f'<div class="thumb">'
        f'<img src="{png}" alt="{title} annual chart thumbnail" '
        f'loading="lazy">'
        f'</div>'
        f'<div class="card-body">'
        f'<h2>{title}</h2>'
        f'<p>{subtitle}</p>'
        f'<span class="cta">Open interactive chart →</span>'
        f'</div>'
        f'</a>'
    )


def _render_calendar_card() -> str:
    # A tiny row of "upcoming" tiles + tick marks — styled so it reads
    # as an earnings calendar strip without needing live data.
    accent = "#8E44AD"
    strip = "".join(
        '<span class="cal-tile">'
        f'<span class="cal-dot" style="background:{COLORS.get(t, "#888")};"></span>'
        f'<span class="cal-lbl">{t}</span>'
        '</span>'
        for t in ("AMZN", "MSFT", "GOOGL", "ORCL", "META")
    )
    return (
        f'<a class="card preview-card" href="calendar.html" '
        f'style="--accent:{accent};">'
        f'<div class="thumb thumb-mock">'
        f'<div class="cal-mock">'
        f'<div class="cal-mock-hdr">Upcoming earnings</div>'
        f'<div class="cal-strip">{strip}</div>'
        f'<div class="cal-mock-hdr muted">Recent · last 30 days</div>'
        f'<div class="cal-bars">'
        f'<span class="cal-bar" style="width:80%;"></span>'
        f'<span class="cal-bar" style="width:55%;"></span>'
        f'<span class="cal-bar" style="width:70%;"></span>'
        f'</div>'
        f'</div>'
        f'</div>'
        f'<div class="card-body">'
        f'<h2>Earnings Calendar</h2>'
        f'<p>Upcoming + recent filings across the 13 trackers, with links '
        f'through to each filing on SEC EDGAR / HKEXnews.</p>'
        f'<span class="cta">Open calendar →</span>'
        f'</div>'
        f'</a>'
    )


