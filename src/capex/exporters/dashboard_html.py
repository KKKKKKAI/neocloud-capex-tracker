"""Dashboard landing page (docs/index.html).

Renders a responsive grid of preview cards — one card per subpage — so
a first-time visitor sees every surface at a glance and can click into
the interactive version. Four chart cards embed the matplotlib PNG
thumbnails generated by ``charts.py``; the Calendar and Treatments
cards use inline SVG mock-ups because they don't have a natural PNG
representation.

All four chart cards link to the interactive Plotly pages (`cloud.html`,
`revenue.html`, `capex.html`, `operating_cash_flow.html`). The nav bar
at the top reuses ``_build_nav_html`` so every page on the site shares
the same pill layout; the dashboard lights up the "Home" pill.
"""
